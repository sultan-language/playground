// Reads SultanC's keyword, type and identifier tables from the compiler's own
// sources, which every checkout of the compiler repository contains:
//
//   compiler/frontend/lexer/keywords/keyword_registry.sn     keyword spellings per token
//   compiler/frontend/lexer/keywords/deprecated_registry.sn  old spellings still accepted
//   compiler/frontend/types/builtins_generated.sn            built-in type names
//   compiler/frontend/types/contextual_names_generated.sn    vector / option / result
//   compiler/frontend/lexer/identifiers.sn                   identifier start / rest scalars
//   compiler/frontend/identifier_identity.sn                 ignored and normalized scalars
//
// These files are generated by the compiler's registry generator, so their
// shape is regular; every pattern below fails loudly when it finds nothing.
import { readFile } from "node:fs/promises";
import path from "node:path";

const sortRanges = (list) => list.sort((a, b) => a[0] - b[0]);
const isArabic = (s) => /[؀-ۿ]/.test(s);

export async function readRegistry(checkout) {
  const read = (p) => readFile(path.join(checkout, p), "utf8").catch(() => {
    throw new Error(`registry: ${p} is missing from the SultanC checkout`);
  });
  const need = (what, list) => { if (!list.length) throw new Error(`registry: no ${what} found; the compiler's generated source may have changed shape`); return list; };

  // Keywords: «spelling» -> token. Each token has one English spelling and one
  // canonical Arabic spelling, plus any deprecated Arabic spellings.
  const kw = await read("compiler/frontend/lexer/keywords/keyword_registry.sn");
  const byToken = new Map();
  for (const m of kw.matchAll(/«([^»]+)»\)\)\s*\{\s*أرجع\s+مطابقة_كلمة\.محجوزة\(رمز\.([^\s(]+)\(\)\)/g)) {
    if (!byToken.has(m[2])) byToken.set(m[2], []);
    byToken.get(m[2]).push(m[1]);
  }
  need("keywords", [...byToken.keys()]);
  const dep = await read("compiler/frontend/lexer/keywords/deprecated_registry.sn");
  const deprecated = new Set([...dep.matchAll(/القديمة:\s*«([^»]+)»/g)].map((m) => m[1]));

  const pairs = [], deprecatedPairs = [], spellingsOf = new Map();
  for (const [token, spellings] of byToken) {
    const en = spellings.find((s) => !isArabic(s));
    const arabic = spellings.filter(isArabic);
    const canonical = arabic.find((s) => !deprecated.has(s));
    if (!en || !canonical) continue;
    pairs.push([canonical, en]);
    for (const old of arabic.filter((s) => s !== canonical)) deprecatedPairs.push([old, en]);
    spellingsOf.set(canonical, spellings);
  }

  // Boolean literals.
  const literals = [];
  const bools = { true: [], false: [] };
  for (const m of kw.matchAll(/«([^»]+)»\)\)\s*\{\s*أرجع\s+مطابقة_كلمة\.منطقية\((صواب|خطأ)\)/g)) {
    bools[m[2] === "صواب" ? "true" : "false"].push(m[1]);
  }
  for (const list of Object.values(bools)) {
    const en = list.find((s) => !isArabic(s)), ar = list.find(isArabic);
    if (en && ar) { pairs.push([ar, en]); literals.push(ar, en); }
  }
  need("boolean literals", literals);

  // Built-in types: the Arabic display names, with all spellings of their tokens.
  const builtins = await read("compiler/frontend/types/builtins_generated.sn");
  const types = [];
  for (const m of builtins.matchAll(/أرجع\s+«([^»]+)»;/g)) {
    const all = spellingsOf.get(m[1]);
    if (all) types.push(...all);
  }
  need("built-in types", types);

  // Contextual types: vector, option, result (and deprecated spellings).
  const ctx = await read("compiler/frontend/types/contextual_names_generated.sn");
  for (const m of ctx.matchAll(/عرف\s+تهجئة_عرض_(\S+?)_مدمجة\(\):\s*نص\s*\{\s*أرجع\s+«([^»]+)»;/g)) {
    const en = ctx.match(new RegExp(`تهجئة_عرض_${m[1]}_مدمجة_إنجليزية\\(\\):\\s*نص\\s*\\{\\s*أرجع\\s+«([^»]+)»;`));
    if (!en) continue;
    pairs.push([m[2], en[1]]);
    types.push(m[2], en[1]);
  }
  for (const block of ctx.split(/\n(?=عام عرف)/)) {
    const names = [...block.matchAll(/اسم_مقنن_يطابق_نصا_سياقيا\([^«]*«([^»]+)»\)/g)].map((m) => m[1]);
    if (names.length < 3) continue;
    const en = names.find((s) => !isArabic(s));
    const canonical = pairs.find(([, e]) => e === en)?.[0];
    for (const old of names.filter((s) => isArabic(s) && s !== canonical)) { deprecatedPairs.push([old, en]); types.push(old); }
  }

  // Identifier rules.
  const ids = await read("compiler/frontend/lexer/identifiers.sn");
  const fn = (src, name) => {
    const start = src.indexOf(`عرف ${name}(`);
    if (start < 0) return "";
    const next = src.indexOf("\nعام عرف", start + 1);
    return src.slice(start, next < 0 ? undefined : next);
  };
  const ranges = (body) => sortRanges([
    ...[...body.matchAll(/>=\s*0x([0-9A-Fa-f]+)\)\s*&&\s*\(القيمة\s*<=\s*0x([0-9A-Fa-f]+)/g)].map((m) => [parseInt(m[1], 16), parseInt(m[2], 16)]),
    ...[...body.matchAll(/القيمة\s*==\s*0x([0-9A-Fa-f]+)\)\)/g)].map((m) => [parseInt(m[1], 16), parseInt(m[1], 16)]),
  ]);
  const identity = await read("compiler/frontend/identifier_identity.sn");
  const identifier = {
    start: need("identifier start scalars", ranges(fn(ids, "بداية_معرف"))),
    rest: need("identifier rest scalars", ranges(fn(ids, "تتمة_معرف"))),
    ignored: [...fn(identity, "محرف_تهجئة_معرف").matchAll(/==\s*0x([0-9A-Fa-f]+)/g)].map((m) => parseInt(m[1], 16)),
    normalized: [...fn(identity, "طبع_محرف_هوية_معرف").matchAll(/==\s*0x([0-9A-Fa-f]+)\)\s*\{\s*أرجع\s+0x([0-9A-Fa-f]+)/g)].map((m) => [parseInt(m[1], 16), parseInt(m[2], 16)]),
  };

  return { pairs, deprecatedPairs, types: [...new Set(types)], literals, identifier };
}
